"""Fit shared controls of our pen paths to local M proof images.

The reference font is used only to render review masks. Its glyph contours are
never read or copied into the result. A held-out set is reported separately.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import subprocess
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.spatial import cKDTree
from skimage.morphology import skeletonize
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'outputs/handwriting/pen-m'
SOURCE = ROOT / 'assets/fonts/classj-pen-m/source.js'
KNOTS = 6


def references():
    result = {}
    for path in sorted((ROOT / 'outputs/handwriting').rglob('DXKPM-M-*.ttf')):
        with TTFont(path) as f:
            for cp in f.getBestCmap():
                if 0xac00 <= cp <= 0xd7a3:
                    result[chr(cp)] = str(path)
    # Some preview cmap entries are blank placeholders for unsupported syllables.
    return {char: file for char, file in result.items() if mask(file, char).any()}


def records(chars):
    js = "const F=require(process.argv[1]);console.log(JSON.stringify(Array.from(process.argv[2],c=>({char:c,parts:F.rawComponents(c).map(p=>({...p,key:F.correctionGroup(c,p),paths:p.paths.map(s=>F.sample(s,64))}))}))));"
    return json.loads(subprocess.check_output(['node', '-e', js, str(SOURCE), ''.join(chars)], encoding='utf-8'))


def basis(t):
    t = np.minimum(np.asarray(t) * (KNOTS - 1), KNOTS - 1 - 1e-8)
    i = t.astype(int)
    b = np.zeros((len(t), KNOTS))
    b[np.arange(len(t)), i] = 1 - (t - i)
    b[np.arange(len(t)), i + 1] = t - i
    return b


def mask(file, char, size=400):
    im = Image.new('L', (size + 48, size + 48))
    ImageDraw.Draw(im).text((24, 24 + .8 * size), char,
                           font=ImageFont.truetype(str(file), size), fill=255, anchor='ls')
    return np.asarray(im) > 127


def fit(iterations=12, holdout=False):
    refs = references()
    recs = records(refs)
    OUT.mkdir(parents=True, exist_ok=True)
    groups = defaultdict(list)
    basis64 = basis(np.linspace(0, 1, 64))
    training = []
    heldout = []
    for rec in recs:
        char = rec['char']
        # A fixed 20% split, independent of the quality of an individual glyph.
        if holdout and ord(char) % 5 == 3:
            heldout.append(char)
            continue
        training.append(char)
        yy, xx = np.where(skeletonize(mask(refs[char], char)))
        target = np.c_[(xx - 24) / 4, (yy - 24) / 4]
        paths, identities = [], []
        for part in rec['parts']:
            for index, path in enumerate(part['paths']):
                paths.append(np.array(path))
                identities.append((part['key'], index, len(part['paths'])))
        tree = cKDTree(np.concatenate(paths))
        dist, near = tree.query(target)
        for pi, (path, identity) in enumerate(zip(paths, identities)):
            assigned = target[(near // 64 == pi) & (dist < 11)]
            if len(assigned) < 8:
                continue
            closed = np.linalg.norm(path[0] - path[-1]) < .1
            # The entry hook is generated by the pen, not by the centerline.
            direction = path[3] - path[0]
            if not closed and direction[1] > 2 * abs(direction[0]):
                assigned = assigned[((assigned - path[0]) @ direction) >= -.5]
            if len(assigned) < 8:
                continue
            groups[identity].append((path, assigned, closed, char))
    controls = {}
    stats = []
    for identity, examples in groups.items():
        delta = np.zeros((KNOTS, 2))
        regularizer = np.eye(KNOTS) * 1.5
        curvature = np.diff(np.eye(KNOTS), n=2, axis=0) * 4
        for _ in range(iterations):
            matrices = [regularizer, curvature]
            targets = [np.zeros((KNOTS, 2)), np.zeros((KNOTS - 2, 2))]
            for original, target, closed, char in examples:
                current = original + basis64 @ delta
                # Both directions preserve coverage as well as the ink center.
                dist, ids = cKDTree(target).query(current)
                weights = np.sqrt(np.minimum(1, 2 / np.maximum(dist, .1)))
                matrices.append(basis64 * weights[:, None])
                targets.append((target[ids] - original) * weights[:, None])
                dist, ids = cKDTree(current).query(target)
                weights = np.sqrt(.6 * np.minimum(1, 3 / np.maximum(dist, .1)))
                matrices.append(basis64[ids] * weights[:, None])
                targets.append((target - original[ids]) * weights[:, None])
                if closed:
                    continuity = np.zeros((1, KNOTS))
                    continuity[0, 0], continuity[0, -1] = 20, -20
                    matrices.append(continuity)
                    targets.append(np.zeros((1, 2)))
            next_delta = np.linalg.lstsq(np.concatenate(matrices), np.concatenate(targets), rcond=None)[0]
            delta = .25 * delta + .75 * np.clip(next_delta, -8, 8)
        key, index, count = identity
        if key not in controls:
            controls[key] = [np.zeros((KNOTS, 2)).tolist() for _ in range(count)]
        controls[key][index] = np.round(delta, 3).tolist()
        stats.append({'key': key, 'stroke': index, 'examples': len(examples), 'maxShift': float(np.linalg.norm(delta, axis=1).max())})
    text = SOURCE.read_text(encoding='utf-8')
    text = re.sub(r'const M_REFINEMENTS = .*?;\n',
                  'const M_REFINEMENTS = ' + json.dumps(controls, ensure_ascii=False, separators=(',', ':')) + ';\n', text, count=1)
    SOURCE.write_text(text, encoding='utf-8')
    (OUT / 'fit-report.json').write_text(json.dumps({'training': training, 'heldout': heldout, 'groups': stats}, ensure_ascii=False, indent=2), encoding='utf-8')
    (OUT / 'reference-map.json').write_text(json.dumps(refs, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'training': len(training), 'heldout': len(heldout), 'groups': len(controls), 'strokes': len(stats)}))


def review():
    refs = references()
    report = json.loads((OUT / 'fit-report.json').read_text(encoding='utf-8'))
    after = ROOT / 'assets/fonts/classj-pen-m/ClassJPenM-Regular.ttf'
    before = OUT / 'before.ttf'
    rows = []
    for char, ref in refs.items():
        target = mask(ref, char, 200)
        old, new = mask(before, char, 200), mask(after, char, 200)
        iou = lambda x: float((x & target).sum() / (x | target).sum())
        rows.append({'char': char, 'before': iou(old), 'after': iou(new), 'heldout': char in report['heldout']})
    aggregate = {}
    for key, subset in [('all', rows), ('heldout', [r for r in rows if r['heldout']]), ('training', [r for r in rows if not r['heldout']])]:
        if not subset:
            continue
        aggregate[key] = {'count': len(subset), 'beforeInkIoU': float(np.mean([r['before'] for r in subset])), 'afterInkIoU': float(np.mean([r['after'] for r in subset]))}
    (OUT / 'metrics.json').write_text(json.dumps({'summary': aggregate, 'glyphs': rows}, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(aggregate, ensure_ascii=False))
    lines = ['가나다라마바사아자차카타파하', '아야어여오요우유으이', '까따빠싸짜애얘에예', '와왜외워웨위의', '나무바다하늘꽃구름', '학교친구연필책가방', '나는나를믿어요', '각간갈감강같갚갖갗갛', '권괄괜괌괭괵균귤퀄쾅', '확활훤휜뺨뼈뻐쌍땅짝찜찹핥팥', '값넋앉닭삶읽밟읊']
    ui = ImageFont.truetype('C:/Windows/Fonts/malgun.ttf', 18)
    for batch in range(3):
        section = lines[batch * 4: batch * 4 + 4]
        im = Image.new('RGB', (1600, len(section) * 380 + 65), '#fffefa')
        d = ImageDraw.Draw(im)
        d.text((24, 15), '같은 112px · 같은 기준선 / 원본 M → 기존 자체 서체 → 새 M 시안', font=ui, fill='#566461')
        for li, line in enumerate(section):
            for fi, label in enumerate(['원본 M', '기존', '새 M']):
                y = 55 + li * 380 + fi * 120
                d.text((14, y + 44), label, font=ui, fill='#566461')
                x = 105
                for char in line:
                    file = refs[char] if fi == 0 else before if fi == 1 else after
                    f = ImageFont.truetype(str(file), 112)
                    d.text((x, y + 100), char, font=f, fill='#253b35', anchor='ls')
                    x += f.getlength(char)
                d.line((100, y + 100, 1575, y + 100), fill='#e2e8e3')
        file = OUT / f'comparison-{batch + 1}.webp'
        im.save(file, lossless=True)
        with Image.open(file) as decoded:
            assert im.size == decoded.size and im.tobytes() == decoded.convert('RGB').tobytes()


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--review', action='store_true')
    p.add_argument('--iterations', type=int, default=15)
    p.add_argument('--holdout', action='store_true')
    args = p.parse_args()
    review() if args.review else fit(args.iterations, args.holdout)
