"""Map original atlas label/dot positions to curated interactive place IDs.

Run after build-world-history-figures.py. No latitude/longitude is inferred.
Overrides below were checked against the original printed city dots/stars.
"""
import json,math,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OVERRIDES={
 'alexander':{'알렉산드리아':[406.5,596]},
 'india':{'간다라':[257.4,175.4]},
 'sui-canal':{'강도(양저우)':[272.203,298.401]},
 'islam':{'바그다드':[418.033,218.284]},
 'tang':{'탈라스':[492,505]},
 'edo':{'에도(도쿄)':[494.849,308.413]},
 'mughal':{'아그라':[435.871,175.588]},
 'napoleon':{'워털루':[278.5,150.5]},
 'ww1':{'사라예보':[312,400.5]},
 'southeast-asia':{'싱가포르':[418,607]},
}
def build():
 scenes=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {SCENES} from './learning/inquiry/globe/history/content.mjs'; console.log(JSON.stringify(SCENES));"],cwd=ROOT,encoding='utf-8'))
 metadata={r['id']:r for r in json.loads((ROOT/'.tmp/world-history/figure-labels.json').read_text(encoding='utf-8'))}
 needs={};cities={}
 def include(fid,places):
  needs.setdefault(fid,set()).update(p['point'] for p in places)
  cities.setdefault(fid,set()).update(p['point'] for p in places if not p.get('region'))
 for scene in scenes:
  include(scene['figure'],scene['places'])
  for step in scene.get('steps',[]):include(step['figure'],step.get('places',scene['places']))
  for q in scene['questions']:needs.setdefault(q.get('figure',scene['figure']),set()).update(p[0] for p in q['marks'])
 figures={}
 for fid,keys in needs.items():
  data=metadata[fid];points={}
  for key in sorted(keys):
   labels=[r for r in data['labels'] if r['text'].strip()==key]
   if not labels:raise ValueError(f'Missing source label: {fid} / {key}')
   x,y,x2,y2=labels[0]['rect'];point=[(x+x2)/2,(y+y2)/2]
   if key in cities.get(fid,set()) and data['dots']:
    dot=min(data['dots'],key=lambda d:math.dist(point,d))
    if math.dist(point,dot)<=24:point=dot
   point=OVERRIDES.get(fid,{}).get(key,point)
   points[key]=[round(v,3) for v in point]
  figures[fid]={'crop':data['crop'],'points':points}
 (ROOT/'learning/inquiry/globe/history/figures.mjs').write_text('// Generated by scripts/build-world-history-points.py; original PDF page coordinates.\nexport const FIGURES='+json.dumps(figures,ensure_ascii=False,indent=1)+';\n',encoding='utf-8')
 print(f'{len(figures)} figures, {sum(len(f["points"]) for f in figures.values())} curated points')
if __name__=='__main__':build()
