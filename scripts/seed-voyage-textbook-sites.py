def add(id,name,kind,lat,lon,country,topic,levels,objective,in1520,source,facts,reach='land',city=None,built=None):
    row=dict(id=id,name=name,kind=kind,lat=lat,lon=lon,todayCountry=country,reach=reach,
             in1520=in1520,text=' '.join(f[0] for f in facts),sources=[{'title':source[0],'url':source[1]}])
    if city:
        row.update(cityId=city,status='later',built=built)
    if built:row['built']=built
    sites['cityLandmarks' if city else 'discoveries'].append(row)
    sites['questions'][id]=[[q,answer,wrong.split('|'),sentence] for sentence,q,answer,wrong in facts]
    learning['entries'][id]={'tier':'later' if built else 'core','topic':topic,'levels':levels,
                             'objective':objective,'valuable':False}


