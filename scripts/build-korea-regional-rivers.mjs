const linesOf = geometry => geometry.type === 'LineString' ? [geometry.coordinates] : geometry.coordinates;
const round = line => line.map(p => p.map(n => +n.toFixed(5)));
const digest = text => createHash('sha256').update(text).digest('hex');
// Natural Earth stops above the wide Yangtze estuary. Retain the actual OSM
// downstream coordinates, splitting each source line rather than joining gaps.
const estuary = [];
for (const line of osm.geojson.coordinates) {
  let run = [];
  for (const point of line) {
    if (point[0] >= 119.59) run.push(point);
    else { if (run.length > 1) estuary.push(run); run = []; }
  }
  if (run.length > 1) estuary.push(run);
}
const features = definitions.map(({ names, exclude = [], anchor, ...properties }) => {
  const matched = ne.features.filter(f => names.includes(f.properties.name) && !exclude.includes(f.properties.rivernum));
  if (!matched.length) throw new Error(`No source geometry: ${properties.id}`);
  const coordinates = matched.flatMap(f => linesOf(f.geometry));
  if (properties.id === 'yangtze') coordinates.push(...estuary);
  const rounded = coordinates.map(round);
  const nearest = rounded.flat().reduce((best, point) => Math.hypot(point[0] - anchor[0], point[1] - anchor[1]) < Math.hypot(best[0] - anchor[0], best[1] - anchor[1]) ? point : best);
  return { type: 'Feature', properties: { ...properties, label: nearest, minZoom: properties.id === 'ussuri' ? 5 : 4, sourceParts: matched.map(f => f.properties.dissolve) }, geometry: { type: 'MultiLineString', coordinates: rounded } };
});
