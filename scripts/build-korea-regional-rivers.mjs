// node scripts/build-korea-regional-rivers.mjs .tmp/regional-rivers
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

const input = process.argv[2];
if (!input) throw new Error('Pass the directory containing the two source JSON files.');
const sourceName = 'ne_10m_rivers_lake_centerlines.geojson';
const neRaw = await fs.readFile(path.join(input, sourceName), 'utf8');
const osmRaw = await fs.readFile(path.join(input, 'yangtze-osm.json'), 'utf8');
const ne = JSON.parse(neRaw);
const osm = JSON.parse(osmRaw).find(r => r.osm_type === 'relation' && r.osm_id === 9392345);
if (osm?.geojson?.type !== 'MultiLineString') throw new Error('Missing OSM Yangtze relation 9392345.');
