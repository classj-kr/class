'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const teacher=fs.readFileSync(path.join(root,'public/teacher.html'),'utf8');
assert.match(html,/function drawNaturalEarthLayer\(cw,ch,left,top\)/);
const cacheKey=Number(html.match(/natural-earth-v58\/tiles\/tile_\$\{col\}_\$\{row\}\.webp\?v=(\d+)/)?.[1]);
assert.ok(cacheKey>=58,'tile URL must be tile_${col}_${row}.webp with a cache key');
assert.match(teacher,/natural-earth-v58\/overview\.webp\?v=\d+/);
assert.doesNotMatch(html,/ocean_original_tiles/);
console.log(JSON.stringify({ok:true,naturalEarthRuntime:true,cacheKey}));
