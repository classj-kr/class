'use strict';
// Reviewed comprehension questions: cause, evidence, environment and exchange.
// Each fourth field identifies the supporting sentence in the actual reading.
const Catalog=require('./mission-catalog');
const stories=require('../data/catalog/city-stories.json');
const cities=Catalog.PLACES.filter(p=>p.isOriginalCity).map(p=>({...p,text:(stories.find(s=>s.cityId===p.id)?.sections||Catalog.ADDITIONAL_SETTLEMENTS.find(s=>s.id===p.id)?.story.sections||[]).map(s=>s.text).join(' ')}));
const readings=new Map([...Catalog.DISCOVERIES,...Catalog.CITY_LANDMARKS,...cities].map(x=>[x.id,x]));
const result={};
const errors=[];
function add(id,rows){
  const item=readings.get(id);if(!item)throw Error('문항의 장소 누락: '+id);
  result[id]=rows.map(([prompt,answer,wrong,hint])=>{
    const text=[item.text,item.in1520].filter(Boolean).join('\n');
    const evidence=text.split(/(?<=[.!?])\s+|\n/).find(s=>s.includes(hint));
    if(!evidence)errors.push(id+'의 문항 근거 누락: '+hint);
    return [prompt,answer,wrong.split(' / '),evidence];
  });
}
