"""Build a small, local SVG outline from the app's Natural Earth country geometry."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'data/atlas-countries.json').read_text(encoding='utf8'))
paths=[]
for f in data['features']:
 g=f['geometry']; polygons=g['coordinates'] if g['type']=='MultiPolygon' else [g['coordinates']]
 for poly in polygons:
  ring=poly[0]
  paths.append('M'+'L'.join(f'{x:g},{-y:g}' for x,y in ring)+'Z')
(root/'data/study-outline.mjs').write_text('// Natural Earth outline; generated by tools/build-study-outline.py.\nexport const WORLD_PATH='+json.dumps(''.join(paths))+';\n',encoding='utf8')
