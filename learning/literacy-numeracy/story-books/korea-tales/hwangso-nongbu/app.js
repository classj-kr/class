/* 보기는 책을 열 때마다 자리를 바꾼다. 답의 자리를 외워 버리면 문제가 아니게 된다.
   섞는 것은 그리는 차례뿐이고, 채점은 data-choice 에 담긴 원래 번호로 한다.
   한 번 정한 차례는 책을 닫을 때까지 그대로다. 쪽을 오갈 때마다 바뀌면 헷갈린다. */
function shuffledOrder(n) {
    const a = [...Array(n).keys()];
    for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
}

/* 보기 차례는 한글 문항 수로 정한다. 영어판도 보기 개수가 같고,
   QZ 는 이 줄보다 아래에서 만들어져 여기서 부르면 책이 열리지 않는다. */
const QUIZ_ORDER = QUIZ.map(q => shuffledOrder(q.choices.length));
/* 고른 것을 기억해 둔다. 쪽을 옮기면 문제 쪽이 통째로 다시 그려지는데,
   그때 표시가 사라지면 아이가 처음부터 다시 풀어야 한다. */
const QUIZ_PICKED = new Array(QUIZ.length).fill(null);
const QUIZ_WRONG = QUIZ.map(() => new Set());

function quizPage() {
    const items = QZ().map((item, i) => {
        const graded = QUIZ_PICKED[i] !== null;
        const cls = ci => (graded && ci === item.answer) ? ' correct'
            : (QUIZ_WRONG[i].has(ci) ? ' incorrect' : '');
        return `
        <div class="quiz-item${graded ? ' graded' : ''}" data-qindex="${i}">
            <p class="quiz-question">${i + 1}. ${item.q}</p>
            <div class="quiz-choices${item.wide ? ' quiz-choices-stack' : ''}">
                ${QUIZ_ORDER[i].map(ci => `<button type="button" class="quiz-choice${cls(ci)}" data-choice="${ci}">${item.choices[ci]}</button>`).join('')}
            </div>
        </div>`;
    }).join('');
    return `
        <div class="page page-quiz">
            <h2>${T().quiz}</h2>
            <p class="quiz-intro-text" id="quizProgress">${T().done(QUIZ_PICKED.filter(v => v !== null).length, QZ().length)}</p>
            <div class="quiz-list">${items}</div>
        </div>`;
}


function afterPage(spread, isFirst) {
    const head = isFirst ? `<h2>${AF().title}</h2>` : '';
    // 그림은 오른쪽 칸 맨 위 모서리에 꽉 붙인다. 학습 허브로 가는 길은 그 칸 맨 아래에 둔다.
    const art = spread.art ? `<div class="after-art">${artFrame(spread.art, AF().emoji)}</div>` : '';
    const foot = spread.last ? `<p class="after-home"><a class="home-btn" href="../../../../../">${T().home}</a></p>` : '';
    const n = spread.left.length;
    const col = (ps, from) => ps.map((t, i) => `<p data-say="${from + i}">${t}</p>`).join('');
    return `
        <div class="page page-after">
            <div class="after-col after-col-left">
                ${head}
                ${col(spread.left, 0)}
            </div>
            <div class="after-col after-col-right${spread.art ? ' after-col-image' : ''}">
                ${art}
                ${readBtnHtml()}
                ${col(spread.right, n)}
                ${foot}
            </div>
        </div>`;
}

const TWO_PAGE_KINDS = new Set(['spread', 'cover', 'after']);

let PAGES = [];
let FOLIOS = [];

function buildPages() {
    const after = AF();
    PAGES = [
        { kind: 'cover' },
        ...CH().flatMap(chapter => chapter.beats.map((beat, i) => ({ kind: 'spread', chapter, beat, isFirst: i === 0 }))),
        ...(HAS_HISTORY ? [{ kind: 'history' }] : []),
        { kind: 'quiz' },
        ...after.spreads.map((spread, i) => ({ kind: 'after', spread, isFirst: i === 0, last: i === after.spreads.length - 1 })),
    ];
    let folioCounter = 0;
    FOLIOS = PAGES.map(p => {
        const width = TWO_PAGE_KINDS.has(p.kind) ? 2 : 1;
        const start = folioCounter + 1;
        folioCounter += width;
        return { start, width };
    });
}

buildPages();

function renderPage(page) {
    switch (page.kind) {
        case 'cover':
            return coverPage();
        case 'spread':
            return spreadPage(page.chapter, page.beat, page.isFirst);
        case 'after':
            return afterPage({ ...page.spread, last: page.last }, page.isFirst);
        case 'history':
            return historyPage();
        case 'quiz':
            return quizPage();
        default:
            return '';
    }
}

