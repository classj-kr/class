const roleOf = p => (typeof p === 'string' ? 'narration' : (p.v || 'narration'));

/* 속도는 넷 다 같다. 읽다가 대사에서 갑자기 빨라지면 귀에 턱턱 걸리고,
   대사야말로 아이가 알아들어야 할 자리라 늦추면 늦췄지 빠르게 할 이유가 없다.
   인물 구분은 음높이에만 맡긴다. */
const SAY_RATE = 0.85;

const SAY_AS = {
    narration: { pitch: 1.00, rate: SAY_RATE, want: 'any' },
    boy:       { pitch: 1.40, rate: SAY_RATE, want: 'male' },
    girl:      { pitch: 1.45, rate: SAY_RATE, want: 'female' },
    woman:     { pitch: 1.15, rate: SAY_RATE, want: 'female' },
    mother:    { pitch: 1.20, rate: SAY_RATE, want: 'female' },
    granny:    { pitch: 1.05, rate: SAY_RATE, want: 'female' },
    man:       { pitch: 0.80, rate: SAY_RATE, want: 'male' },
    old:       { pitch: 0.72, rate: SAY_RATE, want: 'male' },
    beast:     { pitch: 0.60, rate: SAY_RATE, want: 'male' }
};

const VOICES = { any: null, male: null, female: null };

function pickVoices() {
    // 이 자리는 CAN_SPEAK 선언보다 앞이라 직접 확인한다.
    if (typeof speechSynthesis === 'undefined') return;
    const vs = speechSynthesis.getVoices().filter(v => /^en/i.test(v.lang));
    if (!vs.length) return;
    VOICES.any = vs.find(v => /^en[-_]US/i.test(v.lang)) || vs[0];
    VOICES.female = vs.find(v => /samantha|karen|moira|tessa|victoria|zira|serena|allison|ava|susan|fiona|joanna|female|woman/i.test(v.name)) || null;
    VOICES.male = vs.find(v => /daniel|alex|fred|tom|david|oliver|arthur|aaron|matthew|guy|ryan|male|man/i.test(v.name)) || null;
}

if (typeof speechSynthesis !== 'undefined') {
    pickVoices();
    speechSynthesis.onvoiceschanged = pickVoices;
}

function dressVoice(u, role) {
    const a = SAY_AS[role] || SAY_AS.narration;
    u.pitch = a.pitch;
    u.rate = a.rate;
    const want = VOICES[a.want] || VOICES.any;
    if (want) u.voice = want;
}

/* ── 읽어 주기 ─────────────────────────────────────────────────
   펼침면 글을 왼쪽부터 차례로 읽는다. 읽는 문단에 표시가 따라간다.
   다시 누르면 멈춘다. 쪽을 넘기거나 우리말로 돌아가면 저절로 멈춘다. */
let reading = false;
let readToken = 0;

function stopReading() {
    reading = false;
    if (typeof spreadEl !== 'undefined' && spreadEl) spreadEl.classList.remove('is-reading');
    readToken++;
    if (CAN_SPEAK) { try { speechSynthesis.cancel(); } catch (e) {} }
    document.querySelectorAll('.saying').forEach(el => el.classList.remove('saying'));
    const b = document.getElementById('readBtn');
    if (b) b.textContent = '▶';
}

function readPage(from) {
    const page = PAGES[current];
    if (!CAN_SPEAK || !page) return;
    const parts = pageParts(page);
    if (!parts.length) return;
    // 읽던 것이 있으면 끊는다. 안 그러면 새 글이 뒤에 줄을 선다.
    try { speechSynthesis.cancel(); } catch (e) {}
    reading = true;
    if (spreadEl) spreadEl.classList.add('is-reading');
    const mine = ++readToken;
    const btn = document.getElementById('readBtn');
    if (btn) btn.textContent = '■';

    const step = (i) => {
        if (mine !== readToken) return;
        document.querySelectorAll('.saying').forEach(el => el.classList.remove('saying'));
        if (i >= parts.length) { stopReading(); return; }
        const here = document.querySelector(`[data-say="${i}"]`);
        if (here) {
            here.classList.add('saying');
            // 아래쪽 문단이 칸 밖에 있으면 끌어올린다
            here.scrollIntoView({ block: 'nearest' });
        }
        const u = new SpeechSynthesisUtterance(textOf(parts[i]).replace(/"/g, ''));
        u.lang = 'en-US';
        dressVoice(u, roleOf(parts[i]));
        u.onend = () => step(i + 1);
        u.onerror = () => step(i + 1);
        try { speechSynthesis.speak(u); } catch (e) { stopReading(); }
    };
    step(Math.max(0, Math.min(from | 0, parts.length - 1)));
}

/* ── 단어장 ────────────────────────────────────────────────────
   책 아래에 있는 또 한 장의 화면이다. 책은 손대지 않는다.
   펼침면을 넘기면 그 쪽에 나온 낱말로 따라 바뀐다. 영어로 읽을 때만 생긴다. */
const vocabScreenEl = document.getElementById('vocabScreen');
const vocabPanelEl = document.getElementById('vocabPanel');
const scrollDownEl = document.getElementById('scrollDown');
const HAS_WORDS = HAS_EN && EN.words && Object.keys(EN.words).length > 0;
const HAS_WORDS_KO = typeof WORDS_KO !== 'undefined' && WORDS_KO && Object.keys(WORDS_KO).length > 0;

function vocabFor() {
    const all = LANG === 'en' ? ((HAS_WORDS && EN.words) || {}) : ((HAS_WORDS_KO && WORDS_KO) || {});
    const page = PAGES[current];
    // 그 쪽에 실제로 있는 글의 낱말을, 글에 나온 차례대로 보여 준다.
    const key = !page ? null
        : page.kind === 'spread' ? page.beat.art
        : page.kind === 'cover' ? 'cover'
        : page.kind === 'after' ? 'after'
        : null;
    if (key) return { list: all[key] || [] };     // 어려운 말이 없는 쪽은 빈 채로 둔다
    // 문제 쪽에는 글이 없으니 책에 나온 낱말을 다 보여 준다.
    const list = [];
    (all.cover || []).forEach(w => list.push(w));
    CH().forEach(ch => ch.beats.forEach(b => (all[b.art] || []).forEach(w => list.push(w))));
    (all.after || []).forEach(w => list.push(w));
    return { list };
}

function renderVocab() {
    const { list } = vocabFor();
    // 그 쪽에 보여 줄 낱말이 하나도 없으면 단추도 판도 내지 않는다.
    const on = (LANG === 'en' ? HAS_WORDS : HAS_WORDS_KO) && list.length > 0;
    if (vocabScreenEl) vocabScreenEl.hidden = !on;
    if (scrollDownEl) {
        scrollDownEl.hidden = !on;
        scrollDownEl.textContent = T().wordsDown || (LANG === 'en' ? 'Words ⌄' : '낱말 ⌄');
    }
    if (!on) {
        if (window.scrollY) window.scrollTo({ top: 0 });
        return;
    }
    VOCAB_NOW = list;
    vocabPanelEl.innerHTML = `
        <ul class="vocab-list">
            ${list.map((w, i) => `
            <li>
                <div class="vocab-top">
                    <p class="vocab-word">${w.w}</p>
                    ${(CAN_SPEAK && LANG === 'en') ? `<button type="button" class="vocab-say" data-i="${i}" aria-label="Listen">🔊</button>` : ''}
                </div>
                <p class="vocab-mean">${w.k}</p>
                <p class="vocab-sent">${w.s}</p>
            </li>`).join('')}
        </ul>`;
}

/* 듣기 — 낱말을 먼저 읽고, 이어서 그 낱말이 나온 구절을 읽는다.
   목소리가 없는 기기에서는 단추 자체가 뜨지 않는다. */
const CAN_SPEAK = typeof speechSynthesis !== 'undefined';
let VOCAB_NOW = [];

function sayWord(item) {
    if (!CAN_SPEAK || !item) return;
    try {
        speechSynthesis.cancel();
        // 「shook out (shake out)」처럼 괄호로 적어 둔 기본형은 읽지 않는다.
        const bare = item.w.replace(/\s*\([^)]*\)/g, '').trim();
        const 말 = LANG === 'en' ? 'en-US' : 'ko-KR';
        const word = new SpeechSynthesisUtterance(bare);
        word.lang = 말;
        dressVoice(word, 'narration');
        word.rate = 0.75;
        const sent = new SpeechSynthesisUtterance(item.s);
        sent.lang = 말;
        dressVoice(sent, 'narration');
        speechSynthesis.speak(word);
        speechSynthesis.speak(sent);
    } catch (e) { /* 소리를 못 내는 기기도 있다 */ }
}

if (vocabPanelEl) {
    vocabPanelEl.addEventListener('click', e => {
        const btn = e.target.closest('.vocab-say');
        if (btn) sayWord(VOCAB_NOW[Number(btn.dataset.i)]);
    });
}

/* 그림선 — 그림 칸이 끝나는 자리다. 여기까지만 내려가면 글과 단어장이 함께 보인다.
   아래 화면 높이를 딱 그만큼 주면 더 내려갈 데가 없어져 저절로 그 자리에 걸린다. */
function artLine() {
    const page = PAGES[current];
    // 쪽마다 그림이 끝나는 자리가 경계선이다. 거기까지만 내려가면
    // 그림만 위로 빠지고 읽던 글은 화면에 남는다.
    const el = !page ? null
        : page.kind === 'spread' ? document.querySelector('.spread-art')
        : page.kind === 'cover' ? document.querySelector('.page-cover .story-page-left-full')
        : page.kind === 'after' ? document.querySelector('.after-art')
        : null;
    if (!el) return 0;
    const box = el.getBoundingClientRect();
    const line = box.bottom + window.scrollY;
    const book = document.querySelector('.book');
    if (!book) return Math.max(0, Math.round(line));
    const bookBox = book.getBoundingClientRect();
    // 가로 화면 표지처럼 그림이 책 높이를 거의 다 차지하면 경계선이 곧 책 밑이라
    // 책이 통째로 사라진다. 그때만 책이 절반쯤 남도록 붙든다.
    if (box.height < bookBox.height * 0.8) return Math.max(0, Math.round(line));
    const cap = bookBox.bottom + window.scrollY - Math.round(window.innerHeight * 0.45);
    return Math.max(0, Math.round(Math.min(line, Math.max(cap, 0))));
}

function fitVocabScreen() {
    if (!vocabScreenEl || vocabScreenEl.hidden) return;
    const line = artLine();
    // 펼침면이 아닌 쪽(표지·문제·읽고 나서)에는 그림 칸이 없다. 그때는 내용만큼만 둔다.
    vocabScreenEl.style.minHeight = line ? line + 'px' : '';
}

if (scrollDownEl) {
    scrollDownEl.addEventListener('click', () => {
        fitVocabScreen();
        const line = artLine();
        window.scrollTo({ top: line || document.documentElement.scrollHeight, behavior: 'smooth' });
    });
}

window.addEventListener('resize', () => { window.scrollTo(0, 0); fitVocabScreen(); });

/* 말 바꾸기 — 보던 자리를 그대로 두고 글만 갈아 끼운다. */
const langBtn = document.getElementById('langLink');
function applyLang() {
    if (typeof stopReading === 'function') stopReading();
    document.documentElement.lang = LANG;
    document.title = CV().title;
    if (langBtn) {
        langBtn.hidden = !HAS_EN;
        langBtn.textContent = T().other;
        langBtn.setAttribute('aria-label', T().otherAria);
    }
}
if (langBtn && HAS_EN) {
    langBtn.addEventListener('click', () => {
        LANG = LANG === 'en' ? 'ko' : 'en';
        saveLang(LANG);
        const here = PAGES[current];
        buildPages();
        // 같은 자리로 돌아간다. 쪽 수가 같으므로 번호를 그대로 쓴다.
        current = Math.min(current, PAGES.length - 1);
        if (here && here.kind === 'spread') {
            const i = PAGES.findIndex(p => p.kind === 'spread' && p.beat.art === here.beat.art);
            if (i >= 0) current = i;
        }
        applyLang();
        paint();
    });
}

applyLang();
paint();
