const TWO_PAGE_KINDS = new Set(['spread', 'cover', 'after']);

let PAGES = [];
let FOLIOS = [];

function buildPages() {
    const after = AF();
    PAGES = [
        { kind: 'cover' },
        ...CH().flatMap(chapter => chapter.beats.map((beat, i) => ({ kind: 'spread', chapter, beat, isFirst: i === 0 }))),
        ...(HAS_HISTORY ? [{ kind: 'history' }] : []),
        { kind: 'quiz' },
        ...after.spreads.map((spread, i) => ({ kind: 'after', spread, isFirst: i === 0, last: i === after.spreads.length - 1 })),
    ];
    let folioCounter = 0;
    FOLIOS = PAGES.map(p => {
        const width = TWO_PAGE_KINDS.has(p.kind) ? 2 : 1;
        const start = folioCounter + 1;
        folioCounter += width;
        return { start, width };
    });
}

buildPages();

function renderPage(page) {
    switch (page.kind) {
        case 'cover':
            return coverPage();
        case 'spread':
            return spreadPage(page.chapter, page.beat, page.isFirst);
        case 'after':
            return afterPage({ ...page.spread, last: page.last }, page.isFirst);
        case 'history':
            return historyPage();
        case 'quiz':
            return quizPage();
        default:
            return '';
    }
}

