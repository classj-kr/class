function paint() {
    spreadEl.innerHTML = renderPage(PAGES[current]);
    prevBtn.disabled = current === 0;
    nextBtn.disabled = current === PAGES.length - 1;
    indicatorEl.textContent = `${current + 1} / ${PAGES.length}`;

    const folio = FOLIOS[current];
    folioLeftEl.classList.toggle('folio-center', folio.width === 1);
    if (folio.width === 2) {
        folioLeftEl.textContent = folio.start;
        folioRightEl.textContent = folio.start + 1;
        folioLeftEl.hidden = false;
        folioRightEl.hidden = false;
    } else {
        folioLeftEl.textContent = folio.start;
        folioLeftEl.hidden = false;
        folioRightEl.hidden = true;
    }

    spreadEl.querySelectorAll('[data-goto]').forEach(btn => {
        btn.addEventListener('click', () => {
            const chapterNum = Number(btn.dataset.goto);
            const idx = PAGES.findIndex(p => p.kind === 'spread' && p.chapter.num === chapterNum && p.isFirst);
            if (idx >= 0) goTo(idx);
        });
    });
    spreadEl.querySelectorAll('[data-goto-kind]').forEach(btn => {
        btn.addEventListener('click', () => {
            const idx = PAGES.findIndex(p => p.kind === btn.dataset.gotoKind);
            if (idx >= 0) goTo(idx);
        });
    });

    if (PAGES[current].kind === 'quiz') {
        initQuiz();
    }

    const readBtn = document.getElementById('readBtn');
    if (readBtn) readBtn.addEventListener('click', () => (reading ? stopReading() : readPage(0)));

    // 읽는 중일 때만 문단을 눌러 그 자리로 옮긴다.
    // 그냥 눌렀다고 소리가 나면 곤란하니, 스피커 단추를 누른 뒤에만 먹는다.
    if (LANG === 'en' && CAN_SPEAK) {
        spreadEl.querySelectorAll('[data-say]').forEach(el => {
            el.addEventListener('click', () => {
                if (!reading) return;
                readPage(Number(el.dataset.say));
            });
        });
    }

    renderVocab();
    fitVocabScreen();
    fitAfterword();
}

/* 「읽고 나서」는 글씨를 줄이지 않는다. 세로 화면에서는 끝그림을 접어 두는 것이
   기본이고(styles.css), 여기서 그림을 켜 보아 자리가 남을 때만 그대로 둔다.
   그래서 이 함수가 한 번도 못 돌아도 글이 잘리지는 않는다. */
function fitAfterword() {
    const page = spreadEl.querySelector('.page-after');
    if (!page) return;
    page.classList.add('after-roomy');
    const spills = [...page.querySelectorAll('.after-col')]
        .some(col => col.scrollHeight > col.clientHeight);
    if (spills) page.classList.remove('after-roomy');
}

/* 화면 크기가 바뀌면 다시 잰다. 크기가 한 박자 늦게 잡히는 곳이 있어
   그 자리에서 한 번, 잠시 뒤에 한 번 더 잰다. */
let refitTimer = 0;
function refitAfterword() {
    fitAfterword();
    clearTimeout(refitTimer);
    refitTimer = setTimeout(fitAfterword, 250);
}

window.addEventListener('resize', refitAfterword);
window.addEventListener('orientationchange', refitAfterword);
/* 화면을 돌렸을 때 resize 가 안 잡히는 곳이 있다. 책 상자 크기를 직접 지켜본다. */
if (window.ResizeObserver) {
    const bookEl = document.getElementById('book');
    if (bookEl) new ResizeObserver(refitAfterword).observe(bookEl);
}
if (document.fonts && document.fonts.ready) document.fonts.ready.then(fitAfterword);

function initQuiz() {
    const progressEl = document.getElementById('quizProgress');

    spreadEl.querySelectorAll('.quiz-item').forEach(item => {
        const qi = Number(item.dataset.qindex);
        const q = QZ()[qi];
        item.querySelectorAll('.quiz-choice').forEach(btn => {
            btn.addEventListener('click', () => {
                if (item.classList.contains('graded')) return;
                const chosen = Number(btn.dataset.choice);
                /* 틀리면 그 보기만 빨갛게 남기고, 맞는 것을 고를 때까지 다시 고르게 한다.
                   답을 미리 보여 주면 아이가 생각할 자리가 사라진다. */
                if (chosen !== q.answer) {
                    btn.classList.add('incorrect');
                    QUIZ_WRONG[qi].add(chosen);
                    return;
                }
                btn.classList.add('correct');
                item.classList.add('graded');
                QUIZ_PICKED[qi] = chosen;
                progressEl.textContent = T().done(QUIZ_PICKED.filter(v => v !== null).length, QZ().length);
            });
        });
    });
}

function goTo(index) {
    if (animating || index === current || index < 0 || index >= PAGES.length) return;
    stopReading();
    animating = true;
    const dir = index > current ? 'flip-next' : 'flip-prev';
    spreadEl.classList.add(dir);
    setTimeout(() => {
        current = index;
        paint();
    }, 230);
    setTimeout(() => {
        spreadEl.classList.remove('flip-next', 'flip-prev');
        animating = false;
    }, 480);
}

prevBtn.addEventListener('click', () => goTo(current - 1));
nextBtn.addEventListener('click', () => goTo(current + 1));

