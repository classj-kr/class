function tocPage() {
    const pageOf = num => {
        const idx = PAGES.findIndex(p => p.kind === 'spread' && p.chapter.num === num && p.isFirst);
        return idx >= 0 ? FOLIOS[idx].start : '';
    };
    const itemHtml = s => `
        <li>
            <button type="button" data-goto="${s.num}">
                <span class="toc-num">${s.num}</span>
                <span>
                    <strong>${s.title.replace(/^(\d+장|Chapter \d+) · /, '')}</strong>
                    <small>${T().page(pageOf(s.num))}</small>
                </span>
            </button>
        </li>`;
    const quizIdx = PAGES.findIndex(p => p.kind === 'quiz');
    const quizItemHtml = `
        <li>
            <button type="button" data-goto-kind="quiz">
                <span class="toc-num">❓</span>
                <span>
                    <strong>${T().quiz}</strong>
                    <small>${quizIdx >= 0 ? T().page(FOLIOS[quizIdx].start) : ''}</small>
                </span>
            </button>
        </li>`;
    const afterIdx = PAGES.findIndex(p => p.kind === 'after' && p.isFirst);
    const afterItemHtml = `
        <li>
            <button type="button" data-goto-kind="after">
                <span class="toc-num">📖</span>
                <span>
                    <strong>${T().after}</strong>
                    <small>${afterIdx >= 0 ? T().page(FOLIOS[afterIdx].start) : ''}</small>
                </span>
            </button>
        </li>`;
    const chs = CH();
    const half = Math.ceil(chs.length / 2);
    const leftItems = chs.slice(0, half).map(itemHtml).join('');
    const rightItems = chs.slice(half).map(itemHtml).join('') + quizItemHtml + afterItemHtml;
    return `
        <div class="page page-toc">
            <div class="story-page-left">
                <h2>${T().toc}</h2>
                <ul class="toc-list">${leftItems}</ul>
            </div>
            <div class="story-page-right">
                <h2 class="toc-h2-ghost" aria-hidden="true">${T().toc}</h2>
                <ul class="toc-list">${rightItems}</ul>
            </div>
        </div>`;
}

function spreadPage(chapter, beat, isFirst, isLast) {
    const badgeHtml = isFirst ? `<div class="spread-chapter-badge">${chapter.title}</div>` : '';
    const n = beat.left.length;
    const leftHtml = beat.left.map((p, i) => `<p data-say="${i}">${p}</p>`).join('');
    let rightHtml = beat.right.map((p, i) => `<p data-say="${n + i}">${p}</p>`).join('');
    // 교훈은 오른쪽 칸이 아니라 두 칸 아래 제 자리에 놓는다. 칸 안에 밀어 넣으면 넘친다.
    const moralHtml = isLast && chapter.moral ? `<p class="fable-moral">${chapter.moral}</p>` : '';
    return `
        <div class="page page-story${moralHtml ? ' spread-final' : ''}">
            <div class="spread-art">
                ${badgeHtml}
                ${artFrame(beat.art, beat.emoji)}
                ${readBtnHtml()}
            </div>
            <div class="spread-text">
                <div class="spread-text-left">${leftHtml}</div>
                <div class="spread-text-right">${rightHtml}</div>
                ${moralHtml}
            </div>
        </div>`;
}

