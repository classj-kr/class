const TWO_PAGE_KINDS = new Set(['spread', 'toc', 'cover', 'after']);

/* 말을 바꾸면 쪽을 다시 짠다. 쪽 수는 두 말이 같으므로 보던 자리가 흔들리지 않는다. */
let PAGES = [];
let FOLIOS = [];

function buildPages() {
    const chs = CH();
    PAGES = [
    { kind: 'cover' },
    { kind: 'toc' },
    ...chs.flatMap((chapter, ci) => chapter.beats.map((beat, i) => ({
        kind: 'spread', chapter, beat,
        isFirst: i === 0,
        isLast: ci === chs.length - 1 && i === chapter.beats.length - 1
    }))),
    { kind: 'quiz' },
    ...AF().spreads.map((spread, i) => ({ kind: 'after', spread, isFirst: i === 0 }))
    ];

    let folioCounter = 0;
    FOLIOS = PAGES.map(p => {
        const width = TWO_PAGE_KINDS.has(p.kind) ? 2 : 1;
        const start = folioCounter + 1;
        folioCounter += width;
        return { start, width };
    });
}

function renderPage(page) {
    switch (page.kind) {
        case 'cover':
            return coverPage();
        case 'toc':
            return tocPage();
        case 'spread':
            return spreadPage(page.chapter, page.beat, page.isFirst, page.isLast);
        case 'after':
            return afterPage(page.spread, page.isFirst);
        case 'quiz':
            return quizPage();
        default:
            return '';
    }
}

