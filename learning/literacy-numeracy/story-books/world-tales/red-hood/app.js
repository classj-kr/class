/* 말을 바꾸면 쪽을 다시 짠다. 쪽 수는 두 말이 같으므로 보던 자리가 흔들리지 않는다. */
let PAGES = [];
let FOLIOS = [];

function buildPages() {
    const chs = CH();
    PAGES = [
    { kind: 'cover' },
    { kind: 'toc' },
    ...chs.flatMap((chapter, ci) => chapter.beats.map((beat, i) => ({
        kind: 'spread', chapter, beat,
        isFirst: i === 0,
        isLast: ci === chs.length - 1 && i === chapter.beats.length - 1
    }))),
    { kind: 'quiz' },
    ...AF().spreads.map((spread, i) => ({ kind: 'after', spread, isFirst: i === 0 }))
    ];

    let folioCounter = 0;
    FOLIOS = PAGES.map(p => {
        const width = TWO_PAGE_KINDS.has(p.kind) ? 2 : 1;
        const start = folioCounter + 1;
        folioCounter += width;
        return { start, width };
    });
}

function renderPage(page) {
    switch (page.kind) {
        case 'cover':
            return coverPage();
        case 'toc':
            return tocPage();
        case 'spread':
            return spreadPage(page.chapter, page.beat, page.isFirst, page.isLast);
        case 'after':
            return afterPage(page.spread, page.isFirst);
        case 'quiz':
            return quizPage();
        default:
            return '';
    }
}

let current = 0;
let animating = false;

const spreadEl = document.getElementById('spread');
const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');
const indicatorEl = document.getElementById('pageIndicator');
const folioLeftEl = document.getElementById('folioLeft');
const folioRightEl = document.getElementById('folioRight');

function paint() {
    spreadEl.innerHTML = renderPage(PAGES[current]);
    prevBtn.disabled = current === 0;
    nextBtn.disabled = current === PAGES.length - 1;
    indicatorEl.textContent = `${current + 1} / ${PAGES.length}`;

    const folio = FOLIOS[current];
    folioLeftEl.classList.toggle('folio-center', folio.width === 1);
    if (folio.width === 2) {
        folioLeftEl.textContent = folio.start;
        folioRightEl.textContent = folio.start + 1;
        folioLeftEl.hidden = false;
        folioRightEl.hidden = false;
    } else {
        folioLeftEl.textContent = folio.start;
        folioLeftEl.hidden = false;
        folioRightEl.hidden = true;
    }

    spreadEl.querySelectorAll('[data-goto]').forEach(btn => {
        btn.addEventListener('click', () => {
            const chapterNum = Number(btn.dataset.goto);
            const idx = PAGES.findIndex(p => p.kind === 'spread' && p.chapter.num === chapterNum && p.isFirst);
            if (idx >= 0) goTo(idx);
        });
    });
    spreadEl.querySelectorAll('[data-goto-kind]').forEach(btn => {
        btn.addEventListener('click', () => {
            const idx = PAGES.findIndex(p => p.kind === btn.dataset.gotoKind);
            if (idx >= 0) goTo(idx);
        });
    });

    if (PAGES[current].kind === 'quiz') {
        initQuiz();
    }

    const readBtn = document.getElementById('readBtn');
    if (readBtn) readBtn.addEventListener('click', () => (reading ? stopReading() : readPage(0)));

    // 읽는 중일 때만 문단을 눌러 그 자리로 옮긴다.
    if (LANG === 'en' && CAN_SPEAK) {
        spreadEl.querySelectorAll('[data-say]').forEach(el => {
            el.addEventListener('click', () => {
                if (!reading) return;
                readPage(Number(el.dataset.say));
            });
        });
    }
    if (typeof renderVocab === 'function') renderVocab();
}

function initQuiz() {
    const progressEl = document.getElementById('quizProgress');

    spreadEl.querySelectorAll('.quiz-item').forEach(item => {
        const qi = Number(item.dataset.qindex);
        const q = QZ()[qi];
        item.querySelectorAll('.quiz-choice').forEach(btn => {
            btn.addEventListener('click', () => {
                if (item.classList.contains('graded')) return;
                const ci = Number(btn.dataset.choice);
                // 맞힐 때까지 다시 고를 수 있다. 틀린 것만 빨갛게 남는다.
                // 답을 미리 보여 주면 아이가 생각할 자리가 사라진다.
                if (ci !== q.answer) {
                    btn.classList.add('incorrect');
                    (QUIZ_WRONG[QK(qi)] = QUIZ_WRONG[QK(qi)] || []).push(ci);
                    return;
                }
                btn.classList.add('correct');
                item.classList.add('graded');
                QUIZ_DONE[QK(qi)] = true;
                progressEl.textContent = T().done(quizDone(), QZ().length);
            });
        });
    });
}

function goTo(index) {
    if (animating || index === current || index < 0 || index >= PAGES.length) return;
    stopReading();
    animating = true;
    const dir = index > current ? 'flip-next' : 'flip-prev';
    spreadEl.classList.add(dir);
    setTimeout(() => {
        current = index;
        paint();
    }, 230);
    setTimeout(() => {
        spreadEl.classList.remove('flip-next', 'flip-prev');
        animating = false;
    }, 480);
}

prevBtn.addEventListener('click', () => goTo(current - 1));
nextBtn.addEventListener('click', () => goTo(current + 1));

document.getElementById('tocLink').addEventListener('click', () => {
    const idx = PAGES.findIndex(p => p.kind === 'toc');
    if (idx >= 0) goTo(idx);
});

document.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowRight') goTo(current + 1);
    if (e.key === 'ArrowLeft') goTo(current - 1);
});

/* ── 목소리 ────────────────────────────────────────────────────
   기기에 있는 영어 목소리를 골라 쓴다. 없으면 기본 목소리로 읽는다. */
const textOf = p => (typeof p === 'string' ? p : p.t);

/* 읽기 단추 — 표지·펼침면·읽고 나서에 붙는다. 영어로 볼 때만 나온다. */
function readBtnHtml() {
    return (LANG === 'en' && CAN_SPEAK)
        ? `<button type="button" class="read-btn" id="readBtn">${reading ? '■' : '▶'}</button>`
        : '';
}

/* 그 쪽에서 읽어 줄 글. 화면에 보이는 차례 그대로다. */
function pageParts(page) {
    if (!page) return [];
    if (page.kind === 'spread') return page.beat.left.concat(page.beat.right);
    if (page.kind === 'cover') return [CV().title].concat(CV().intro);
    if (page.kind === 'after') return page.spread.left.concat(page.spread.right);
    return [];
}

const SAY_RATE = 0.85;
const VOICES = { any: null };

function pickVoices() {
    if (typeof speechSynthesis === 'undefined') return;
    const vs = speechSynthesis.getVoices().filter(v => /^en/i.test(v.lang));
    if (!vs.length) return;
    VOICES.any = vs.find(v => /^en[-_]US/i.test(v.lang)) || vs[0];
}

if (typeof speechSynthesis !== 'undefined') {
    pickVoices();
    speechSynthesis.onvoiceschanged = pickVoices;
}

function dressVoice(u) {
    u.rate = SAY_RATE;
    if (VOICES.any) u.voice = VOICES.any;
}

/* ── 읽어 주기 ─────────────────────────────────────────────────
   펼침면 글을 왼쪽부터 차례로 읽는다. 읽는 문단에 표시가 따라간다.
   다시 누르면 멈춘다. 쪽을 넘기거나 우리말로 돌아가면 저절로 멈춘다. */
let reading = false;
let readToken = 0;

function stopReading() {
    reading = false;
    if (typeof spreadEl !== 'undefined' && spreadEl) spreadEl.classList.remove('is-reading');
    readToken++;
    if (CAN_SPEAK) { try { speechSynthesis.cancel(); } catch (e) {} }
    document.querySelectorAll('.saying').forEach(el => el.classList.remove('saying'));
    const b = document.getElementById('readBtn');
    if (b) b.textContent = '▶';
}

function readPage(from) {
    const page = PAGES[current];
    if (!CAN_SPEAK || !page) return;
    const parts = pageParts(page);
    if (!parts.length) return;
    try { speechSynthesis.cancel(); } catch (e) {}
    reading = true;
    if (spreadEl) spreadEl.classList.add('is-reading');
    const mine = ++readToken;
    const btn = document.getElementById('readBtn');
    if (btn) btn.textContent = '■';

    const step = (i) => {
        if (mine !== readToken) return;
        document.querySelectorAll('.saying').forEach(el => el.classList.remove('saying'));
        if (i >= parts.length) { stopReading(); return; }
        const here = document.querySelector(`[data-say="${i}"]`);
        if (here) {
            here.classList.add('saying');
            here.scrollIntoView({ block: 'nearest' });
        }
        const u = new SpeechSynthesisUtterance(textOf(parts[i]).replace(/"/g, ''));
        u.lang = 'en-US';
        dressVoice(u);
        u.onend = () => step(i + 1);
        u.onerror = () => step(i + 1);
        try { speechSynthesis.speak(u); } catch (e) { stopReading(); }
    };
    step(Math.max(0, Math.min(from | 0, parts.length - 1)));
}

/* ── 단어장 — 영어로 읽을 때만 책 아래에 깔린다 ──────────────────── */
const vocabScreenEl = document.getElementById('vocabScreen');
const vocabPanelEl = document.getElementById('vocabPanel');
const scrollDownEl = document.getElementById('scrollDown');
const HAS_WORDS = HAS_EN && EN.words && Object.keys(EN.words).length > 0;
const HAS_WORDS_KO = typeof WORDS_KO !== 'undefined' && WORDS_KO && Object.keys(WORDS_KO).length > 0;

/* 듣기 — 낱말을 먼저 읽고, 이어서 그 낱말이 나온 구절을 읽는다.
   목소리가 없는 기기에서는 단추 자체가 뜨지 않는다. */
const CAN_SPEAK = typeof speechSynthesis !== 'undefined';
let VOCAB_NOW = [];

function sayWord(item) {
    if (!CAN_SPEAK || !item) return;
    try {
        speechSynthesis.cancel();
        const bare = String(wOf(item)).replace(/\s*\([^)]*\)/g, '').trim();
        const 말 = LANG === 'en' ? 'en-US' : 'ko-KR';
        const word = new SpeechSynthesisUtterance(bare);
        word.lang = 말;
        word.rate = 0.75;
        const sent = new SpeechSynthesisUtterance(sOf(item));
        sent.lang = 말;
        speechSynthesis.speak(word);
        speechSynthesis.speak(sent);
    } catch (e) { /* 소리를 못 내는 기기도 있다 */ }
}

function vocabFor() {
    const all = LANG === 'en' ? ((HAS_WORDS && EN.words) || {}) : ((HAS_WORDS_KO && WORDS_KO) || {});
    const page = PAGES[current];
    // 그 쪽에 실제로 있는 글의 낱말을, 글에 나온 차례대로 보여 준다.
    const key = !page ? null
        : page.kind === 'spread' ? page.beat.art
        : page.kind === 'after' ? page.spread.art
        : null;
    if (key && all[key]) return all[key];
    // 표지에도 소개글이 있다. 그 글에 나온 낱말만 보여 준다.
    if (page && page.kind === 'cover') return all['cover.webp'] || all['cover'] || [];
    // 차례·문제 쪽에는 글이 없다. 보여 줄 것이 없으면 칸을 접는다.
    return [];
}

/* 낱말 자료는 우리말과 영어가 적는 이름이 다르다. 우리말 쪽은 전래동화와 같은
   {w, k, s}, 영어 쪽은 {word, meaning, sentence}다. 어느 쪽이 와도 읽게 한다. */
const wOf = w => (w.word !== undefined ? w.word : w.w);
const mOf = w => (w.meaning !== undefined ? w.meaning : w.k);
const sOf = w => (w.sentence !== undefined ? w.sentence : w.s);

function renderVocab() {
    const has = LANG === 'en' ? HAS_WORDS : HAS_WORDS_KO;
    const list = has ? vocabFor() : [];
    const on = list.length > 0;
    if (vocabScreenEl) vocabScreenEl.hidden = !on;
    if (scrollDownEl) {
        scrollDownEl.hidden = !on;
        scrollDownEl.textContent = T().wordsDown || (LANG === 'en' ? 'Words ⌄' : '낱말 ⌄');
    }
    if (!on) {
        if (window.scrollY) window.scrollTo({ top: 0 });
        return;
    }
    VOCAB_NOW = list;
    vocabPanelEl.innerHTML = `
        <ul class="vocab-list">
            ${list.map((w, i) => `
            <li>
                <div class="vocab-top">
                    <p class="vocab-word">${wOf(w)}</p>
                    ${(CAN_SPEAK && LANG === 'en') ? `<button type="button" class="vocab-say" data-i="${i}" aria-label="Listen">🔊</button>` : ''}
                </div>
                <p class="vocab-mean">${mOf(w)}</p>
                <p class="vocab-sent">${sOf(w)}</p>
            </li>`).join('')}
        </ul>`;
    fitVocabScreen();
}

if (vocabPanelEl) {
    vocabPanelEl.addEventListener('click', e => {
        const btn = e.target.closest('.vocab-say');
        if (btn) sayWord(VOCAB_NOW[Number(btn.dataset.i)]);
    });
}

/* 그림선 — 그림 칸이 끝나는 자리다. 여기까지만 내려가면 그림만 위로 빠지고
   읽던 글은 화면에 남는다. 아래 화면 높이를 딱 그만큼 주면 더 내려갈 데가
   없어져 저절로 그 자리에 걸린다. */
function artLine() {
    const page = PAGES[current];
    const el = !page ? null
        : page.kind === 'spread' ? document.querySelector('.spread-art')
        : page.kind === 'cover' ? document.querySelector('.page-cover .story-page-left-full')
        : page.kind === 'after' ? document.querySelector('.after-art')
        : null;
    if (!el) return 0;
    const box = el.getBoundingClientRect();
    const line = box.bottom + window.scrollY;
    const book = document.querySelector('.book');
    if (!book) return Math.max(0, Math.round(line));
    const bookBox = book.getBoundingClientRect();
    // 그림이 책 높이를 거의 다 차지하면 경계선이 곧 책 밑이라 책이 통째로
    // 사라진다. 그때만 책이 절반쯤 남도록 붙든다.
    if (box.height < bookBox.height * 0.8) return Math.max(0, Math.round(line));
    const cap = bookBox.bottom + window.scrollY - Math.round(window.innerHeight * 0.45);
    return Math.max(0, Math.round(Math.min(line, Math.max(cap, 0))));
}

function fitVocabScreen() {
    if (!vocabScreenEl || vocabScreenEl.hidden) return;
    const line = artLine();
    // 펼침면이 아닌 쪽(차례·문제)에는 그림 칸이 없다. 그때는 내용만큼만 둔다.
    vocabScreenEl.style.minHeight = line ? line + 'px' : '';
}

if (scrollDownEl) {
    scrollDownEl.addEventListener('click', () => {
        fitVocabScreen();
        const line = artLine();
        window.scrollTo({ top: line || document.documentElement.scrollHeight, behavior: 'smooth' });
    });
}

window.addEventListener('resize', () => { window.scrollTo(0, 0); fitVocabScreen(); });

/* 말 바꾸기 — 보던 자리를 그대로 두고 글만 갈아 끼운다. */
const langBtn = document.getElementById('langLink');
function applyLang() {
    if (typeof stopReading === 'function') stopReading();
    document.documentElement.lang = LANG;
    document.title = CV().title;
    if (langBtn) {
        langBtn.hidden = !HAS_EN;
        langBtn.textContent = T().other;
        langBtn.setAttribute('aria-label', T().otherAria);
    }
}
if (langBtn && HAS_EN) {
    langBtn.addEventListener('click', () => {
        LANG = LANG === 'en' ? 'ko' : 'en';
        saveLang(LANG);
        const here = PAGES[current];
        buildPages();
        current = Math.min(current, PAGES.length - 1);
        // 보던 그림 그대로 선다. 쪽 수가 같으므로 그림 파일 이름으로 찾는다.
        if (here && here.kind === 'spread') {
            const i = PAGES.findIndex(p => p.kind === 'spread' && p.beat.art === here.beat.art);
            if (i >= 0) current = i;
        }
        applyLang();
        paint();
    });
}

buildPages();
applyLang();
paint();

