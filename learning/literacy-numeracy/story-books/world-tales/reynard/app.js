function sayWord(item) {
    if (!CAN_SPEAK || !item) return;
    try {
        speechSynthesis.cancel();
        const bare = String(wOf(item)).replace(/\s*\([^)]*\)/g, '').trim();
        const 말 = LANG === 'en' ? 'en-US' : 'ko-KR';
        const word = new SpeechSynthesisUtterance(bare);
        word.lang = 말;
        word.rate = 0.75;
        const sent = new SpeechSynthesisUtterance(sOf(item));
        sent.lang = 말;
        speechSynthesis.speak(word);
        speechSynthesis.speak(sent);
    } catch (e) { /* 소리를 못 내는 기기도 있다 */ }
}

function vocabFor() {
    const all = LANG === 'en' ? ((HAS_WORDS && EN.words) || {}) : ((HAS_WORDS_KO && WORDS_KO) || {});
    const page = PAGES[current];
    // 그 쪽에 실제로 있는 글의 낱말을, 글에 나온 차례대로 보여 준다.
    const key = !page ? null
        : page.kind === 'spread' ? page.beat.art
        : page.kind === 'after' ? page.spread.art
        : null;
    if (key && all[key]) return all[key];
    // 표지에도 소개글이 있다. 그 글에 나온 낱말만 보여 준다.
    if (page && page.kind === 'cover') return all['cover.webp'] || all['cover'] || [];
    // 차례·문제 쪽에는 글이 없다. 보여 줄 것이 없으면 칸을 접는다.
    return [];
}

/* 낱말 자료는 우리말과 영어가 적는 이름이 다르다. 우리말 쪽은 전래동화와 같은
   {w, k, s}, 영어 쪽은 {word, meaning, sentence}다. 어느 쪽이 와도 읽게 한다. */
const wOf = w => (w.word !== undefined ? w.word : w.w);
const mOf = w => (w.meaning !== undefined ? w.meaning : w.k);
const sOf = w => (w.sentence !== undefined ? w.sentence : w.s);

function renderVocab() {
    const has = LANG === 'en' ? HAS_WORDS : HAS_WORDS_KO;
    const list = has ? vocabFor() : [];
    const on = list.length > 0;
    if (vocabScreenEl) vocabScreenEl.hidden = !on;
    if (scrollDownEl) {
        scrollDownEl.hidden = !on;
        scrollDownEl.textContent = T().wordsDown || (LANG === 'en' ? 'Words ⌄' : '낱말 ⌄');
    }
    if (!on) {
        if (window.scrollY) window.scrollTo({ top: 0 });
        return;
    }
    VOCAB_NOW = list;
    vocabPanelEl.innerHTML = `
        <ul class="vocab-list">
            ${list.map((w, i) => `
            <li>
                <div class="vocab-top">
                    <p class="vocab-word">${wOf(w)}</p>
                    ${(CAN_SPEAK && LANG === 'en') ? `<button type="button" class="vocab-say" data-i="${i}" aria-label="Listen">🔊</button>` : ''}
                </div>
                <p class="vocab-mean">${mOf(w)}</p>
                <p class="vocab-sent">${sOf(w)}</p>
            </li>`).join('')}
        </ul>`;
    fitVocabScreen();
}

if (vocabPanelEl) {
    vocabPanelEl.addEventListener('click', e => {
        const btn = e.target.closest('.vocab-say');
        if (btn) sayWord(VOCAB_NOW[Number(btn.dataset.i)]);
    });
}

/* 그림선 — 그림 칸이 끝나는 자리다. 여기까지만 내려가면 그림만 위로 빠지고
   읽던 글은 화면에 남는다. 아래 화면 높이를 딱 그만큼 주면 더 내려갈 데가
   없어져 저절로 그 자리에 걸린다. */
function artLine() {
    const page = PAGES[current];
    const el = !page ? null
        : page.kind === 'spread' ? document.querySelector('.spread-art')
        : page.kind === 'cover' ? document.querySelector('.page-cover .story-page-left-full')
        : page.kind === 'after' ? document.querySelector('.after-art')
        : null;
    if (!el) return 0;
    const box = el.getBoundingClientRect();
    const line = box.bottom + window.scrollY;
    const book = document.querySelector('.book');
    if (!book) return Math.max(0, Math.round(line));
    const bookBox = book.getBoundingClientRect();
    // 그림이 책 높이를 거의 다 차지하면 경계선이 곧 책 밑이라 책이 통째로
    // 사라진다. 그때만 책이 절반쯤 남도록 붙든다.
    if (box.height < bookBox.height * 0.8) return Math.max(0, Math.round(line));
    const cap = bookBox.bottom + window.scrollY - Math.round(window.innerHeight * 0.45);
    return Math.max(0, Math.round(Math.min(line, Math.max(cap, 0))));
}

function fitVocabScreen() {
    if (!vocabScreenEl || vocabScreenEl.hidden) return;
    const line = artLine();
    // 펼침면이 아닌 쪽(차례·문제)에는 그림 칸이 없다. 그때는 내용만큼만 둔다.
    vocabScreenEl.style.minHeight = line ? line + 'px' : '';
}

if (scrollDownEl) {
    scrollDownEl.addEventListener('click', () => {
        fitVocabScreen();
        const line = artLine();
        window.scrollTo({ top: line || document.documentElement.scrollHeight, behavior: 'smooth' });
    });
}

window.addEventListener('resize', () => { window.scrollTo(0, 0); fitVocabScreen(); });

/* 말 바꾸기 — 보던 자리를 그대로 두고 글만 갈아 끼운다. */
const langBtn = document.getElementById('langLink');
function applyLang() {
    if (typeof stopReading === 'function') stopReading();
    document.documentElement.lang = LANG;
    document.title = CV().title;
    if (langBtn) {
        langBtn.hidden = !HAS_EN;
        langBtn.textContent = T().other;
        langBtn.setAttribute('aria-label', T().otherAria);
    }
}
if (langBtn && HAS_EN) {
    langBtn.addEventListener('click', () => {
        LANG = LANG === 'en' ? 'ko' : 'en';
        saveLang(LANG);
        const here = PAGES[current];
        buildPages();
        current = Math.min(current, PAGES.length - 1);
        // 보던 그림 그대로 선다. 쪽 수가 같으므로 그림 파일 이름으로 찾는다.
        if (here && here.kind === 'spread') {
            const i = PAGES.findIndex(p => p.kind === 'spread' && p.beat.art === here.beat.art);
            if (i >= 0) current = i;
        }
        applyLang();
        paint();
    });
}

