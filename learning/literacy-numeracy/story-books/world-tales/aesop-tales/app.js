function buildPages() {
    const chs = CH();
    PAGES = [
    { kind: 'cover' },
    { kind: 'toc' },
    ...chs.flatMap(fable => fable.beats.map((beat, i) => ({ kind: 'spread', fable, beat, isFirst: i === 0, isLast: i === fable.beats.length - 1 }))),
    { kind: 'quiz' },
    ...AF().spreads.map((spread, i) => ({ kind: 'after', spread, isFirst: i === 0 }))
    ];

    let folioCounter = 0;
    FOLIOS = PAGES.map(p => {
        const width = TWO_PAGE_KINDS.has(p.kind) ? 2 : 1;
        const start = folioCounter + 1;
        folioCounter += width;
        return { start, width };
    });
}

function renderPage(page) {
    switch (page.kind) {
        case 'cover':
            return coverPage();
        case 'toc':
            return tocPage();
        case 'spread':
            return spreadPage(page.fable, page.beat, page.isFirst, page.isLast);
        case 'after':
            return afterPage(page.spread, page.isFirst);
        case 'quiz':
            return quizPage();
        default:
            return '';
    }
}

