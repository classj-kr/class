//  - 원이 커지면 원주율도 커진다고 여긴다. 지름을 모르면 원주율을 견줄 수 없다고 여긴다.
//  - 반지름이 2배가 되면 넓이도 2배가 된다고 여긴다.
//  - 반원·원의 4분의 1의 둘레에서 곧은 변(지름, 반지름 둘)을 빠뜨린다. 운동장 모양의 둘레에는 직사각형의 세로까지 더한다.
//  - 정사각형·직사각형 안에 꼭 맞는 원의 지름이 어느 변과 같은지 모른다(직사각형은 짧은 변이다). 원 안의 정사각형은 한 변을 몰라 넓이를 구할 수 없다고 여긴다.
//  - 원을 잘라 이어 붙인 직사각형의 가로를 원주(전체)로 본다.
//  - 고리나 길에서 반지름의 차·지름에서 너비를 한 번만 뺀 값으로 원의 넓이를 구한다.
//
// 실력 문항의 잣대: 두 가지만 둔다.
//  ① 문제의 상황·그림에 함정이 있어 뜻을 정확히 대야 풀리는 문제. 어려움은 보기가 아니라 그림과 상황에서 나온다(유형마다 「어떤 아이가 틀리는가」를 적었다).
