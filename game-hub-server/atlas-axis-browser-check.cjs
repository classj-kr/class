const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{}),args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:950}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/globe/app.js?*',async route=>{const response=await route.fetch();await route.fulfill({response,body:await response.text()+'\nwindow.__axisMap=map;'});});
  await page.goto('http://127.0.0.1:5179/learning/inquiry/globe/');
  await page.waitForFunction(()=>window.__axisMap?.getLayer('axis-latitudes'));
  const original=await page.evaluate(()=>({center:__axisMap.getCenter().toArray(),zoom:__axisMap.getZoom()}));
  assert.equal(await page.locator('#axisView').textContent(),'자전축 보기');
  assert.equal(await page.locator('#axisDiagram').isVisible(),false);
  await page.locator('#axisView').click();
  await page.waitForFunction(()=>Math.abs(__axisMap.getRoll()-23.5)<.01&&!__axisMap.isMoving());
  await page.waitForTimeout(450);
  const state=await page.evaluate(()=>({roll:__axisMap.getRoll(),lat:__axisMap.getCenter().lat,n:__axisMap.project([__axisMap.getCenter().lng,90]),s:__axisMap.project([__axisMap.getCenter().lng,-90]),width:__axisMap.getCanvas().clientWidth,height:__axisMap.getCanvas().clientHeight}));
  console.log('Geometry',state);
  assert.equal(state.lat,0);
  assert.equal(await page.locator('#axisView').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.axis-reference').evaluate(el=>getComputedStyle(el).display),'inline');
  await page.screenshot({path:'tmp/axis-desktop.png'});
  await page.locator('#axisView').click();
  await page.waitForFunction(()=>__axisMap.getRoll()===0&&!__axisMap.isMoving());
  const restored=await page.evaluate(()=>({center:__axisMap.getCenter().toArray(),zoom:__axisMap.getZoom()}));
  assert.ok(Math.abs(original.zoom-restored.zoom)<.001);
  original.center.forEach((x,i)=>assert.ok(Math.abs(x-restored.center[i])<.001));
  await page.locator('#axisView').click();
  await page.waitForFunction(()=>!__axisMap.isMoving());
  await page.getByRole('button',{name:'평면지도',exact:true}).click();
  await page.waitForFunction(()=>__axisMap.getProjection().type==='mercator');
  assert.equal(await page.locator('#axisDiagram').isVisible(),false);
  assert.equal(await page.locator('#axisView').isVisible(),false);
  assert.equal(await page.evaluate(()=>__axisMap.getRoll()),0);
  await page.getByRole('button',{name:'지구본',exact:true}).click();
  await page.waitForFunction(()=>__axisMap.getProjection().type==='globe');
  assert.equal(await page.locator('#axisView').getAttribute('aria-pressed'),'false');
  await page.setViewportSize({width:390,height:844});
  await page.reload();await page.waitForFunction(()=>window.__axisMap?.getLayer('axis-latitudes'));
  await page.locator('#axisView').click();await page.waitForFunction(()=>Math.abs(__axisMap.getRoll()-23.5)<.01&&!__axisMap.isMoving());
  await page.waitForTimeout(600);
  await page.screenshot({path:'tmp/axis-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('#resetView').click();await page.waitForFunction(()=>__axisMap.getRoll()===0&&!__axisMap.isMoving());
  assert.equal(await page.locator('#axisDiagram').isVisible(),false);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('#axisView').click();
  assert.equal(await page.evaluate(()=>__axisMap.getRoll()),23.5);
  assert.deepEqual(errors,[]);
  console.log('Axis toggle, restoration, projection, mobile, reset and reduced-motion checks passed.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
